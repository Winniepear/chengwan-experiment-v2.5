import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const cfg=JSON.parse(fs.readFileSync(path.join(root,'config/study.json'),'utf8'));
fs.writeFileSync(path.join(root,'netlify/functions/lib/study-config.mjs'),`// Generated by scripts/sync-config.mjs; edit config/study.json instead.\nexport default ${JSON.stringify(cfg,null,2)};\n`);
fs.writeFileSync(path.join(root,'config/questionnaire_Q13_29items.json'),JSON.stringify(cfg.questionnaire,null,2)+'\n');
console.log(`config synced: ${cfg.wave_id}/${cfg.revision_id}`);
